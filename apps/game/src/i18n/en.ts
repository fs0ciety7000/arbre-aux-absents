/** Verbe d'action selon le périphérique actif (“tap a slot”, “click a slot”…). */
const tap = (d: Device) => (d === 'touch' ? 'tap' : d === 'mouse' ? 'click' : 'select');
const Tap = (d: Device) => {
  const v = tap(d);
  return v.charAt(0).toUpperCase() + v.slice(1);
};

